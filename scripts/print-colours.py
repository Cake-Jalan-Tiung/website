# Converts the brand colours that get printed to CMYK for coated stock, and measures how far
# each conversion lands from the screen colour. Writes src/system/print.generated.ts.
#
#   python3 scripts/print-colours.py
#
# Needs Pillow (LittleCMS) and Adobe's Coated FOGRA39 profile, the ISO 12647-2 reference for coated
# offset, chosen here as a stand-in until a printer names its own. Set CJT_CMYK_PROFILE to use another.
import math
import os
import re
from pathlib import Path

from PIL import Image, ImageCms

ROOT = Path(__file__).resolve().parent.parent
PROFILE = os.environ.get('CJT_CMYK_PROFILE', '/Library/Application Support/Adobe/Color/Profiles/Recommended/CoatedFOGRA39.icc')
PRINTED = ['ink', 'blue', 'cream-400', 'pink']

hexes = dict(re.findall(r"'?([a-z0-9-]+)'?: '(#[0-9A-F]{6})'", (ROOT / 'src/system/tokens.ts').read_text()))


def lab_of_srgb(hex_):
    """sRGB to CIELAB D50 in floating point (IEC 61966-2-1, Bradford adaptation)."""
    def linear(c):
        c /= 255
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (linear(int(hex_[i:i + 2], 16)) for i in (1, 3, 5))
    x = 0.4360747 * r + 0.3850649 * g + 0.1430804 * b
    y = 0.2225045 * r + 0.7168786 * g + 0.0606169 * b
    z = 0.0139322 * r + 0.0971045 * g + 0.7141733 * b
    def f(t):
        return t ** (1 / 3) if t > 216 / 24389 else (24389 / 27 * t + 16) / 116
    fx, fy, fz = f(x / 0.96422), f(y), f(z / 0.82521)
    return (116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz))


def delta_e_2000(lab1, lab2):
    L1, a1, b1 = lab1
    L2, a2, b2 = lab2
    c_bar = (math.hypot(a1, b1) + math.hypot(a2, b2)) / 2
    g = 0.5 * (1 - math.sqrt(c_bar ** 7 / (c_bar ** 7 + 25 ** 7)))
    a1p, a2p = (1 + g) * a1, (1 + g) * a2
    c1p, c2p = math.hypot(a1p, b1), math.hypot(a2p, b2)
    h1p, h2p = math.degrees(math.atan2(b1, a1p)) % 360, math.degrees(math.atan2(b2, a2p)) % 360
    dh = 0 if c1p * c2p == 0 else (h2p - h1p + 180) % 360 - 180
    d_hp = 2 * math.sqrt(c1p * c2p) * math.sin(math.radians(dh / 2))
    l_bar, c_bar_p = (L1 + L2) / 2, (c1p + c2p) / 2
    if c1p * c2p == 0:
        h_bar = h1p + h2p
    elif abs(h1p - h2p) <= 180:
        h_bar = (h1p + h2p) / 2
    else:
        h_bar = (h1p + h2p + 360) / 2 if h1p + h2p < 360 else (h1p + h2p - 360) / 2
    t = 1 - 0.17 * math.cos(math.radians(h_bar - 30)) + 0.24 * math.cos(math.radians(2 * h_bar)) + 0.32 * math.cos(math.radians(3 * h_bar + 6)) - 0.20 * math.cos(math.radians(4 * h_bar - 63))
    rc = 2 * math.sqrt(c_bar_p ** 7 / (c_bar_p ** 7 + 25 ** 7))
    rt = -math.sin(math.radians(60 * math.exp(-(((h_bar - 275) / 25) ** 2)))) * rc
    sl = 1 + 0.015 * (l_bar - 50) ** 2 / math.sqrt(20 + (l_bar - 50) ** 2)
    sc, sh = 1 + 0.045 * c_bar_p, 1 + 0.015 * c_bar_p * t
    dl, dc, dhh = (L2 - L1) / sl, (c2p - c1p) / sc, d_hp / sh
    return math.sqrt(dl ** 2 + dc ** 2 + dhh ** 2 + rt * dc * dhh)


srgb = ImageCms.createProfile('sRGB')
cmyk_profile = ImageCms.getOpenProfile(PROFILE)
to_cmyk = ImageCms.buildTransform(srgb, cmyk_profile, 'RGB', 'CMYK', renderingIntent=ImageCms.Intent.RELATIVE_COLORIMETRIC, flags=ImageCms.Flags.BLACKPOINTCOMPENSATION)
# The CMYK result read back relative to paper white, as the eye adapts to the sheet, so the
# error is the gamut's alone and comparable with the relative screen Lab.
to_lab = ImageCms.buildTransform(cmyk_profile, ImageCms.createProfile('LAB', 5000), 'CMYK', 'LAB', renderingIntent=ImageCms.Intent.RELATIVE_COLORIMETRIC)

rows = []
for name in PRINTED:
    hex_ = hexes[name]
    rgb = tuple(int(hex_[i:i + 2], 16) for i in (1, 3, 5))
    cmyk = ImageCms.applyTransform(Image.new('RGB', (1, 1), rgb), to_cmyk).getpixel((0, 0))
    L, a, b = ImageCms.applyTransform(Image.new('CMYK', (1, 1), cmyk), to_lab).getpixel((0, 0))
    printed = (L * 100 / 255, a - 128, b - 128)
    screen = lab_of_srgb(hex_)
    percent = [round(v * 100 / 255) for v in cmyk]
    rows.append(f"  '{name}': {{cmyk: [{', '.join(map(str, percent))}], lab: [{', '.join(str(round(v)) for v in screen)}], deltaE: {delta_e_2000(screen, printed):.0f}}},")

out = ROOT / 'src/system/print.generated.ts'
out.write_text(
    '// Generated by scripts/print-colours.py. Do not edit; run `python3 scripts/print-colours.py`.\n'
    '// sRGB to Coated FOGRA39 with Adobe\'s profile, relative colorimetric with black point compensation.\n'
    '// lab is the screen colour in CIELAB D50; deltaE is CIEDE2000 between it and the CMYK, both relative to white.\n'
    'export const coatedCmyk = {\n' + '\n'.join(rows) + '\n} as const;\n'
)
print(out.read_text())
